type GrandPrixResultDriverWithoutPosition = Omit<
  GrandPrixResultDriver,
  'position'
>;

const addResultPositions = (
  drivers: GrandPrixResultDriverWithoutPosition[],
  nullPositionDriverIds: number[] = []
): GrandPrixResultDriver[] =>
  drivers.map((driver, index) => ({
    ...driver,
    position: nullPositionDriverIds.includes(driver.driver_id)
      ? null
      : index + 1,
  }));

